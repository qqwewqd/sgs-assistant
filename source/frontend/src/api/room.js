import request from '../utils/request'

export const listIdentityModes = () => request.get('/identity-modes')
export const createRoom = (modeId) => request.post('/rooms', { modeId })
export const joinRoom = (roomCode) => request.post(`/rooms/${roomCode}/join`)
export const getRoom = (roomCode) => request.get(`/rooms/${roomCode}`)
export const startGame = (roomCode) => request.post(`/rooms/${roomCode}/start`)
export const chooseGeneral = (roomCode, generalId, generalSelectIndex = 0) => request.post(`/rooms/${roomCode}/choose`, { generalId, generalSelectIndex })
export const swapGeneral = (roomCode, generalId) => request.post(`/rooms/${roomCode}/swap-general`, { generalId })
export const lockGeneral = (roomCode) => request.post(`/rooms/${roomCode}/lock`)
export const revealGeneral = (roomCode) => request.post(`/rooms/${roomCode}/reveal-general`)
export const drawExtraGeneral = (roomCode, faction, generalId) => request.post(`/rooms/${roomCode}/extra-generals/draw`, { faction, generalId })
export const revealExtraGeneral = (roomCode, index) => request.post(`/rooms/${roomCode}/extra-generals/${index}/reveal`)
export const removeExtraGeneral = (roomCode, index) => request.delete(`/rooms/${roomCode}/extra-generals/${index}`)
export const markDead = (roomCode, targetUserId) => request.post(`/rooms/${roomCode}/dead`, { targetUserId })
export const updateVitals = (roomCode, payload) => request.post(`/rooms/${roomCode}/vitals`, payload)
export const updateMarker = (roomCode, payload) => request.post(`/rooms/${roomCode}/markers`, payload)
export const updateStatus = (roomCode, payload) => request.post(`/rooms/${roomCode}/status`, payload)
export const publishRandomNotice = (roomCode, randomNotice) => request.post(`/rooms/${roomCode}/random-notice`, { randomNotice })
export const appointCrownPrince = (roomCode, targetUserId) => request.post(`/rooms/${roomCode}/crown-prince`, { crownPrinceUserId: targetUserId })
export const restartRoom = (roomCode) => request.post(`/rooms/${roomCode}/restart`)
export const leaveRoom = (roomCode) => request.post(`/rooms/${roomCode}/leave`)
export const dissolveRoom = (roomCode) => request.delete(`/rooms/${roomCode}`)
export const safeLordGenerals = (roomCode, keyword) => request.get(`/rooms/${roomCode}/lord-generals`, { params: { keyword } })
export const manualPickGenerals = (roomCode, keyword) => request.get(`/rooms/${roomCode}/manual-pick-generals`, { params: { keyword } })
export const searchExtraGenerals = (roomCode, keyword, faction) => request.get(`/rooms/${roomCode}/extra-general-candidates`, { params: { keyword, faction } })
